"""Build Android adaptive launcher resources from the approved poster crops."""

import json
from pathlib import Path

from PIL import Image

HERE = Path(__file__).resolve().parent
RES = HERE.parents[3] / "android/app/src/main/res"
WEB_IDENTITY = HERE.parents[3] / "web/public/identity"

# The approved 288px artwork occupies a centered 432px source. At 99dp its
# complete tile is 66dp: Android's guaranteed adaptive-icon safe circle.
# PO #1508 supersedes the former 132dp overscan that clipped the artwork.
MASK_SAFE_FOREGROUND_DP = 99

# Android 12+ splash icons without an icon background use a 288dp canvas whose
# visible area is a centered 192dp circle. A 128dp tile keeps every point of
# the rounded tile, including its corners, inside that circle.
LAUNCH_CANVAS_DP = 288
LAUNCH_TILE_DP = 128
# The approved poster crop carries a square backdrop behind its rounded tile.
# This superellipse (measured from the 350px crop: half-size 175px, exponent
# about 4.3) removes only that backdrop; the tile pixels stay unchanged.
LAUNCH_TILE_EXPONENT = 4.3
LAUNCH_TILE_INSET_PX = 1.5
LAUNCH_SUPERSAMPLE = 4


def launch_tile(source: Image.Image) -> Image.Image:
    """Return the approved tile with its square backdrop made transparent."""
    tile = source.convert("RGBA")
    size = tile.width * LAUNCH_SUPERSAMPLE
    half = size / 2
    radius = half - LAUNCH_TILE_INSET_PX * LAUNCH_SUPERSAMPLE
    mask = Image.new("L", (size, size), 0)
    pixels = mask.load()
    for y in range(size):
        dy = abs(y + 0.5 - half) / radius
        if dy >= 1:
            continue
        reach = radius * (1 - dy**LAUNCH_TILE_EXPONENT) ** (1 / LAUNCH_TILE_EXPONENT)
        for x in range(max(0, int(half - reach)), min(size, int(half + reach) + 1)):
            pixels[x, y] = 255
    mask = mask.resize(tile.size, Image.Resampling.LANCZOS)
    alpha = Image.composite(tile.getchannel("A"), Image.new("L", tile.size, 0), mask)
    tile.putalpha(alpha)
    return tile


def build_launch_icon(catalog: dict) -> None:
    original = next(c for c in catalog["candidates"] if c["id"] == "original")
    with Image.open(HERE / original["file"]) as source:
        tile = launch_tile(source)
    tile.save(RES / "drawable-nodpi" / "launch_icon_tile.png")
    # The Android Web startup view continues the splash with the same pixels.
    tile.save(WEB_IDENTITY / "launch-tile.png")
    (RES / "drawable" / "launch_icon.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by docs/design/eimir/1307-premium-app-icons/build-android-icons.py -->\n'
        '<layer-list xmlns:android="http://schemas.android.com/apk/res/android">\n'
        f'    <item android:width="{LAUNCH_CANVAS_DP}dp" android:height="{LAUNCH_CANVAS_DP}dp">\n'
        '        <shape android:shape="rectangle">\n'
        '            <solid android:color="@android:color/transparent"/>\n'
        '        </shape>\n'
        '    </item>\n'
        '    <item android:drawable="@drawable/launch_icon_tile" '
        f'android:width="{LAUNCH_TILE_DP}dp" '
        f'android:height="{LAUNCH_TILE_DP}dp" '
        'android:gravity="center"/>\n'
        '</layer-list>\n'
    )


def build() -> None:
    catalog = json.loads((HERE / "source-crops.json").read_text())
    drawable = RES / "drawable-nodpi"
    drawable.mkdir(exist_ok=True)
    (RES / "drawable").mkdir(exist_ok=True)
    backgrounds = []
    for candidate in catalog["candidates"]:
        icon_id = candidate["id"]
        with Image.open(HERE / candidate["file"]) as source:
            red, green, blue = source.convert("RGB").getpixel((source.width // 2, 0))
            backgrounds.append(f'    <color name="app_icon_{icon_id}_background">#{red:02X}{green:02X}{blue:02X}</color>')
            # Keep the approved tile pixels unchanged in a stable, centered
            # bitmap. The drawable XML supplies the safe-zone scale.
            canvas = Image.new("RGBA", (432, 432), (0, 0, 0, 0))
            tile = source.convert("RGBA").resize((288, 288), Image.Resampling.LANCZOS)
            canvas.alpha_composite(tile, (72, 72))
            canvas.save(drawable / f"app_icon_{icon_id}_foreground.png")
        # Retain the approved source pixels; the platform owns the outer mask.
        (RES / "drawable" / f"app_icon_{icon_id}_mask_safe.xml").write_text(
            '<?xml version="1.0" encoding="utf-8"?>\n'
            '<layer-list xmlns:android="http://schemas.android.com/apk/res/android">\n'
            f'    <item android:drawable="@drawable/app_icon_{icon_id}_foreground" '
            f'android:width="{MASK_SAFE_FOREGROUND_DP}dp" '
            f'android:height="{MASK_SAFE_FOREGROUND_DP}dp" '
            'android:gravity="center"/>\n'
            '</layer-list>\n'
        )
        (RES / "mipmap-anydpi-v26" / f"app_icon_{icon_id}.xml").write_text(
            '<?xml version="1.0" encoding="utf-8"?>\n'
            '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
            f'    <background android:drawable="@color/app_icon_{icon_id}_background"/>\n'
            f'    <foreground android:drawable="@drawable/app_icon_{icon_id}_mask_safe"/>\n'
            '</adaptive-icon>\n'
        )

    build_launch_icon(catalog)

    (RES / "values" / "app_icon_backgrounds.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n<resources>\n' + "\n".join(backgrounds) + '\n</resources>\n'
    )


if __name__ == "__main__":
    build()
