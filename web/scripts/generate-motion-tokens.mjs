import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

// Static motion values for the motion layer's token adapter (Motion Contract
// M1, #2073): Gesture follow thresholds, the settle spring, the attention
// interval, the unreduced haptics spacing and the opening stage's data hold
// and budget. They do not change with theme,
// token set or reduced motion, so they are generated as constants instead of
// CSS roles. Durations that change with reduced motion stay CSS roles in
// product-roles.css and are read at runtime.
const tokensUrl = new URL('../../design/tokens.json', import.meta.url);
const outputUrl = new URL('../src/motion/tokens.generated.ts', import.meta.url);
const tokens = JSON.parse(readFileSync(tokensUrl, 'utf8'));

function value(path) {
  const node = path.split('.').reduce((current, key) => current?.[key], tokens);
  if (!node || !Object.hasOwn(node, '$value'))
    throw new Error(`Missing token value: ${path}`);
  return node.$value;
}

function number(path) {
  const raw = value(path);
  if (typeof raw !== 'number') throw new Error(`Expected a number: ${path}`);
  return raw;
}

function px(path) {
  const raw = value(path);
  if (typeof raw !== 'string' || !/^\d+(\.\d+)?px$/.test(raw))
    throw new Error(`Expected a pixel dimension: ${path}`);
  return Number.parseFloat(raw);
}

function ms(path) {
  const raw = value(path);
  if (typeof raw !== 'string' || !/^\d+(\.\d+)?ms$/.test(raw))
    throw new Error(`Expected a millisecond duration: ${path}`);
  return Number.parseFloat(raw);
}

function commit(name) {
  return {
    fraction: number(`motion.gesture.commit.${name}.fraction`),
    minPx: px(`motion.gesture.commit.${name}.min`),
    maxPx: px(`motion.gesture.commit.${name}.max`),
  };
}

const generated = {
  gesture: {
    slopPx: px('motion.gesture.slop'),
    axisDominance: number('motion.gesture.axisDominance'),
    reversalCancelPx: px('motion.gesture.reversalCancel'),
    flingVelocityPxPerMs: number('motion.gesture.flingVelocity'),
    flingMinDistancePx: px('motion.gesture.flingMinDistance'),
    edgeResistance: number('motion.gesture.edgeResistance'),
    edgeMaxTravelPx: px('motion.gesture.edgeMaxTravel'),
    commit: {
      pager: commit('pager'),
      sheet: commit('sheet'),
      pull: commit('pull'),
    },
  },
  handwriting: {
    // #2372: font units per millisecond of a message written by hand.
    penSpeedUnitsPerMs: number('motion.handwriting.penSpeed'),
  },
  spring: {
    stiffness: number('motion.spring.settle.stiffness'),
    damping: number('motion.spring.settle.damping'),
    mass: number('motion.spring.settle.mass'),
  },
  attention: {
    sameKindIntervalMs: ms('motion.attention.sameKindInterval'),
  },
  stage: {
    // Motion Contract 4.1 (#2147): the data hold of an opening stage and the
    // budget the hold and the stage share. A wait for data, not motion.
    dataHoldMs: ms('motion.stage.dataHold'),
    openingBudgetMs: ms('motion.stage.openingBudget'),
  },
  haptics: {
    // Motion Contract 4.10: no two haptics within --duration-context. Haptics
    // do not follow reduced motion, so the unreduced value is used.
    minIntervalMs: ms('motion.duration.emphasized'),
  },
};

/** Biome-formatted object literal (unquoted keys, trailing commas). */
function literal(node, indent = '') {
  if (typeof node === 'number') return String(node);
  const inner = `${indent}  `;
  const lines = Object.entries(node).map(
    ([key, child]) => `${inner}${key}: ${literal(child, inner)},`,
  );
  return `{\n${lines.join('\n')}\n${indent}}`;
}

const source = `// Generated by scripts/generate-motion-tokens.mjs from design/tokens.json.
// Do not edit by hand; run npm run tokens:generate.
export const MOTION_CONSTANTS = ${literal(generated)} as const;
`;

const args = process.argv.slice(2);
if (args.length > 1 || (args.length === 1 && args[0] !== '--check'))
  throw new Error('Usage: node scripts/generate-motion-tokens.mjs [--check]');
if (args[0] === '--check') {
  if (readFileSync(outputUrl, 'utf8') !== source)
    throw new Error('Motion constants are stale. Run npm run tokens:generate.');
  console.log('Motion constants match design/tokens.json.');
} else {
  writeFileSync(outputUrl, source);
  console.log(`Generated ${fileURLToPath(outputUrl)}.`);
}
